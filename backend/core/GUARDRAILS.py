# Allow only configured Log Analytics tables and fields in generated queries.
def validate_tables_and_fields(table, fields):

    print(f"{Fore.LIGHTGREEN_EX}Validating Tables and Fields...")
    if table not in ALLOWED_TABLES:
        print(f"{Fore.RED}{Style.BRIGHT}ERROR: " f"Table '{table}' is not in allowed list.{Style.RESET_ALL}")
        raise ValueError(f"Table '{table}' is not in the allowed list.")

    fields = fields.replace(' ','').split(',')

    for field in fields:
        if field not in ALLOWED_TABLES[table]:
            print(f"{Fore.RED}{Style.BRIGHT}ERROR: Field '{field}' is not in allowed list for Table '{table}'.{Style.RESET_ALL}")
            raise ValueError(f"Field '{field}' is not allowed for table '{table}'.")

    print(f"{Fore.WHITE}Fields and tables have been validated and comply with the allowed guidelines.\n")

# Allow only models defined in the project model policy.
def validate_model(model):
    if model not in ALLOWED_MODELS:
        print(f"{Fore.RED}{Style.BRIGHT}ERROR: Model '{model}' is not allowed.{Style.RESET_ALL}")
        raise ValueError(f"Model '{model}' is not in the allowed list.")
    else:
        print(f"{Fore.LIGHTGREEN_EX}Selected model is valid: {Fore.CYAN}{model}\n{Style.RESET_ALL}")
